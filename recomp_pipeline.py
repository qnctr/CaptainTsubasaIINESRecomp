#!/usr/bin/env python3
"""
recomp_pipeline.py — NES ROM → native executable, one command.

Pipeline:
    1. Setup env       — copy framework/ and common/ from NESRecomp
    2. Trim trace      — cut trace.txt to ~2M lines (FCEUX logs are 2GB+)
    3. Generate toml   — parse JSR/JMP, write game.toml
    4. Run NESRecomp   — invoke the recompiler, verify output
    5. Build           — write CMakeLists.txt + game.c from templates,
                         run CMake + MSVC, get .exe

Usage:
    python recomp_pipeline.py --config recomp_config.json
"""
