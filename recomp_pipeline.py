# ============================================================================
# Config
# ============================================================================

@dataclass
class Config:
    rom: Path
    trace: Path
    work: Path
    nesrecomp_dir: Path
    sdl2_dir: Path
    max_trace_lines: int = 2_000_000
    cmake_generator: str = "Visual Studio 17 2022"
    log: Callable[[str], None] = field(default=lambda m: print(m, flush=True))

    def __post_init__(self):
        self.rom = Path(self.rom).resolve()
        self.trace = Path(self.trace).resolve()
        self.work = Path(self.work).resolve()
        self.nesrecomp_dir = Path(self.nesrecomp_dir).resolve()
        self.sdl2_dir = Path(self.sdl2_dir).resolve()

    @classmethod
    def from_config_file(cls, path: Path):
        path = Path(path).resolve()
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
        base = path.parent
        return cls(
            rom=base / data["rom_file"],
            trace=base / data["trace_file"],
            work=Path(data.get("work_dir", str(base))),
            nesrecomp_dir=Path(data.get("nesrecomp_dir", DEFAULT_CONFIG["nesrecomp_dir"])),
            sdl2_dir=Path(data.get("sdl2_dir", DEFAULT_CONFIG["sdl2_dir"])),
            max_trace_lines=data.get("max_trace_lines", DEFAULT_CONFIG["max_trace_lines"]),
            cmake_generator=data.get("cmake_generator", DEFAULT_CONFIG["cmake_generator"]),
        )


# ============================================================================
# Step 1: Setup environment
# ============================================================================

def setup_env(cfg: Config) -> None:
    cfg.log("[1/5] Setting up build environment...")

    exe_candidates = list(cfg.nesrecomp_dir.rglob("nesrecomp.exe"))
    if not exe_candidates:
        raise FileNotFoundError(
            f"nesrecomp.exe not found in {cfg.nesrecomp_dir}.\n"
            f"Download from https://github.com/mstan/nesrecomp/releases"
        )
    cfg.log(f"  -> nesrecomp.exe: {exe_candidates[0]}")

    runner = next((p for p in cfg.nesrecomp_dir.rglob("runner")
                   if p.is_dir() and (p / "src").exists()), None)
    if not runner:
        raise FileNotFoundError(
            f"runner/ not found. The release zip from GitHub has it."
        )

    common = next((p for p in cfg.nesrecomp_dir.rglob("common")
                   if p.is_dir() and any(p.glob("*.h"))), None)
    if not common:
        raise FileNotFoundError(
            f"common/ not found. The release zip from GitHub has it."
        )

    fw = cfg.work / "framework"
    if not (fw / "src").exists():
        cfg.log(f"  -> copying {runner.name}/ -> framework/")
        if fw.exists():
            shutil.rmtree(fw)
        shutil.copytree(runner, fw)
    else:
        cfg.log(f"  ok framework/ already exists")

    cm = cfg.work / "common"
    if not cm.exists():
        cfg.log(f"  -> copying {common.name}/ -> common/")
        shutil.copytree(common, cm)
    else:
        cfg.log(f"  ok common/ already exists")

    if not (cfg.sdl2_dir / "include" / "SDL2").exists():
        raise FileNotFoundError(
            f"SDL2 not found at {cfg.sdl2_dir}/include/SDL2.\n"
            f"Download SDL2-devel-VC from https://github.com/libsdl-org/SDL/releases"
        )
    cfg.log(f"  -> SDL2: {cfg.sdl2_dir}")
    cfg.log("  ok environment ready")


# ============================================================================
# Step 2: Trim trace
# ============================================================================

def trim_trace(cfg: Config) -> Path:
    cfg.log(f"[2/5] Trimming trace to {cfg.max_trace_lines:,} lines...")

    trimmed = cfg.work / "trace_trimmed.txt"
    if trimmed.exists() and trimmed.stat().st_mtime > cfg.trace.stat().st_mtime:
        cfg.log(f"  ok {trimmed.name} is up-to-date")
        return trimmed

    if not cfg.trace.exists():
        raise FileNotFoundError(
            f"Trace file not found: {cfg.trace}.\n"
            f"Record in FCEUX: Debug -> Trace Logger -> Log to File"
        )

    count = 0
    t0 = time.time()
    with open(cfg.trace, "r", encoding="utf-8", errors="ignore") as fin, \
         open(trimmed, "w", encoding="utf-8") as fout:
        for line in fin:
            fout.write(line)
            count += 1
            if count % 500_000 == 0:
                cfg.log(f"    {count:,} lines...")
            if count >= cfg.max_trace_lines:
                break

    elapsed = time.time() - t0
    size_mb = trimmed.stat().st_size / (1024 * 1024)
    cfg.log(f"  ok {count:,} lines -> {trimmed.name} ({size_mb:.1f} MB, {elapsed:.1f}s)")
    return trimmed


# ============================================================================
# Step 3: Generate game.toml
# ============================================================================

def generate_toml(cfg: Config, trace_path: Path) -> Path:
    cfg.log("[3/5] Parsing trace, generating game.toml...")

    with open(cfg.rom, "rb") as f:
        header = f.read(16)
    if header[:4] != b"NES\x1a":
        raise ValueError(f"{cfg.rom.name} is not a NES ROM (no iNES signature)")
    prg_banks = header[4]
    mapper = (header[6] >> 4) | (header[7] & 0xF0)

    if mapper != 4:
        cfg.log(f"  WARNING: mapper {mapper} detected. This pipeline is tuned "
                f"for Mapper 4 (MMC3). Other mappers may need tweaks.")

    addresses = set()
    t0 = time.time()
    with open(trace_path, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            for match in re.finditer(r"(?:JSR|JMP)\s+\$([0-9A-Fa-f]{4})", line):
                addr = int(match.group(1), 16)
                if addr not in (0xC500, 0xFFF0, 0xC506):
                    addresses.add(addr)

    cfg.log(f"  -> {len(addresses):,} unique addresses in {time.time()-t0:.1f}s")

    if len(addresses) < 50:
        cfg.log(f"  WARNING: only {len(addresses)} addresses found. "
                f"Your trace may be too short. Play longer in FCEUX.")

    toml_path = cfg.work / "game.toml"
    with open(toml_path, "w", encoding="utf-8") as f:
        f.write(f'[game]\nname = "{cfg.rom.stem}"\nmapper = {mapper}\n')
        f.write(f'prg_banks = {prg_banks}\n\n')
        f.write("[functions]\nfixed = [\n")
        for addr in sorted(addresses):
            f.write(f"  0x{addr:04X},\n")
        f.write("]\n\n[entrypoints]\n")
        f.write('reset = "0xFFF0"\nnmi = "0xC500"\nirq = "0xC506"\n')

    cfg.log(f"  ok game.toml written ({len(addresses)} functions, mapper {mapper})")
    return toml_path


# ============================================================================
# Step 4: Run NESRecomp
# ============================================================================

def run_nesrecomp(cfg: Config, toml_path: Path) -> None:
    cfg.log("[4/5] Running NESRecomp...")

    exe = next(cfg.nesrecomp_dir.rglob("nesrecomp.exe"))
    out_dir = cfg.work / "generated"
    out_dir.mkdir(exist_ok=True)

    cmd = [
        str(exe), "build",
        "--rom", str(cfg.rom),
        "--output", str(cfg.work),
        "--game", str(toml_path),
        "--force",
    ]
    cfg.log(f"  $ {' '.join(cmd)}")

    t0 = time.time()
    result = subprocess.run(cmd, capture_output=True, text=True, timeout=600)
    elapsed = time.time() - t0

    if result.returncode != 0:
        cfg.log(f"  FAILED code={result.returncode}")
        cfg.log(f"  STDOUT: {result.stdout[-2000:]}")
        cfg.log(f"  STDERR: {result.stderr[-2000:]}")
        raise RuntimeError(f"NESRecomp failed: {result.returncode}")

    c_files = list(out_dir.rglob("*.c"))
    if not c_files:
        raise RuntimeError("No .c files generated")

    m = re.search(r"(\d+) instructions compiled", result.stdout)
    n_insns = m.group(1) if m else "?"
    total_kb = sum(p.stat().st_size for p in c_files) // 1024
    cfg.log(f"  ok {n_insns} instructions, {len(c_files)} .c files, "
            f"{total_kb} KB, {elapsed:.1f}s")

    if n_insns.isdigit() and int(n_insns) < 100:
        cfg.log(f"  WARNING: only {n_insns} instructions compiled. "
                f"Check 'Game config' line in NESRecomp log.")


# ============================================================================
# Step 5: Build
# ============================================================================

def _sanitize_name(name: str) -> str:
    s = re.sub(r"[^A-Za-z0-9_]", "_", name)
    s = re.sub(r"_+", "_", s).strip("_")
    if not s or not s[0].isalpha():
        s = "game_" + s
    return s


def build(cfg: Config) -> Path:
    cfg.log("[5/5] Building executable...")

    project_name = _sanitize_name(cfg.rom.stem)
    cfg.log(f"  -> project: {project_name}")

    excluded_q = " ".join(f'"{n}"' for n in sorted(EXCLUDED_FILES))
    cmake = (CMAKE_TEMPLATE
             .replace("@PROJECT_NAME@", project_name)
             .replace("@SDL2_DIR@", cfg.sdl2_dir.as_posix())
             .replace("@EXCLUDED_NAMES@", excluded_q))
    (cfg.work / "CMakeLists.txt").write_text(cmake, encoding="utf-8")

    game_c = (GAME_C_TEMPLATE
              .replace("@ROM_NAME@", cfg.rom.name)
              .replace("@GAME_TITLE@", cfg.rom.stem))
    (cfg.work / "framework" / "src" / "game.c").write_text(game_c, encoding="utf-8")

    build_dir = cfg.work / "build"
    if build_dir.exists():
        cfg.log("  -> removing old build/")
        shutil.rmtree(build_dir)

    cfg.log(f"  -> cmake configure ({cfg.cmake_generator})...")
    t0 = time.time()
    try:
        subprocess.run(
            ["cmake", "-S", str(cfg.work), "-B", str(build_dir),
             "-G", cfg.cmake_generator, "-A", "x64"],
            check=True, timeout=120,
        )
    except (subprocess.CalledProcessError, FileNotFoundError) as e:
        raise RuntimeError(
            f"CMake configure failed: {e}\n"
            f"Check: Visual Studio 2022, CMake 3.20+, SDL2 at {cfg.sdl2_dir}"
        )
    cfg.log(f"  ok configured in {time.time()-t0:.1f}s")

    cfg.log("  -> cmake build (Release)...")
    t0 = time.time()
    try:
        subprocess.run(
            ["cmake", "--build", str(build_dir), "--config", "Release"],
            check=True, timeout=1800,
        )
    except subprocess.CalledProcessError as e:
        raise RuntimeError(
            f"Build failed: {e}\n"
            f"  LNK2005 -> add file to EXCLUDED_FILES\n"
            f"  LNK2019 -> add stub to game.c template"
        )
    cfg.log(f"  ok built in {time.time()-t0:.1f}s")

    exe = build_dir / "Release" / f"{project_name}.exe"
    if not exe.exists():
        candidates = list(build_dir.rglob("*.exe"))
        if not candidates:
            raise RuntimeError(f"Build done but no .exe in {build_dir}")
        exe = candidates[0]

    size_mb = exe.stat().st_size / (1024 * 1024)
    cfg.log(f"  ok {exe.name} ({size_mb:.1f} MB)")
    return exe


# ============================================================================
# Orchestrator
# ============================================================================

def full_pipeline(cfg: Config) -> Path:
    cfg.log("=" * 60)
    cfg.log("  NES -> native executable")
    cfg.log(f"  ROM:       {cfg.rom}")
    cfg.log(f"  Trace:     {cfg.trace}")
    cfg.log(f"  Work:      {cfg.work}")
    cfg.log(f"  NESRecomp: {cfg.nesrecomp_dir}")
    cfg.log(f"  SDL2:      {cfg.sdl2_dir}")
    cfg.log("=" * 60)

    t0 = time.time()
    setup_env(cfg)
    trimmed = trim_trace(cfg)
    toml = generate_toml(cfg, trimmed)
    run_nesrecomp(cfg, toml)
    exe = build(cfg)

    total = time.time() - t0
    cfg.log("")
    cfg.log("=" * 60)
    cfg.log(f"  SUCCESS in {total:.1f}s")
    cfg.log(f"  Executable: {exe}")
    cfg.log(f"  Next: copy {cfg.rom.name} next to {exe.name}, double-click.")
    cfg.log("=" * 60)
    return exe


# ============================================================================
# CLI
# ============================================================================

def main():
    ap = argparse.ArgumentParser(description="NES -> native executable pipeline")
    ap.add_argument("--config", help="Path to JSON config file")
    ap.add_argument("--rom")
    ap.add_argument("--trace")
    ap.add_argument("--work")
    ap.add_argument("--nesrecomp", default=DEFAULT_CONFIG["nesrecomp_dir"])
    ap.add_argument("--sdl2", default=DEFAULT_CONFIG["sdl2_dir"])
    ap.add_argument("--max-trace-lines", type=int,
                    default=DEFAULT_CONFIG["max_trace_lines"])
    ap.add_argument("--cmake-generator", default=DEFAULT_CONFIG["cmake_generator"])
    args = ap.parse_args()

    if args.config:
        cfg = Config.from_config_file(Path(args.config))
    elif args.rom and args.trace and args.work:
        cfg = Config(
            rom=Path(args.rom), trace=Path(args.trace), work=Path(args.work),
            nesrecomp_dir=Path(args.nesrecomp), sdl2_dir=Path(args.sdl2),
            max_trace_lines=args.max_trace_lines,
            cmake_generator=args.cmake_generator,
        )
    else:
        ap.error("Give --config, or --rom + --trace + --work")

    try:
        full_pipeline(cfg)
    except Exception as e:
        print(f"\nFAILED: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
